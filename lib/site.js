const clone = (x) => JSON.parse(JSON.stringify(x));
const isObj = (x) => x && typeof x === 'object' && !Array.isArray(x);
const HEX = /^#[0-9a-f]{6}$/i;
const IMG_KEY = /(image|photo)$/;
const IMG_OK = /^(https?:\/\/\S+|\/api\/image\?id=\d+)$/i;

// Изчиства записаното от админа спрямо шаблона (непознати ключове отпадат, типовете се налагат)
function sanitize(value, tpl, key = '') {
  if (typeof tpl === 'string') {
    let s = String(value ?? '').slice(0, 4000);
    if (key === 'link') return /^(\/|https?:\/\/)\S*$/.test(s.trim()) ? s.trim() : tpl;
    if (IMG_KEY.test(key)) return s === '' || IMG_OK.test(s.trim()) ? s.trim() : '';
    if (['facebook', 'instagram', 'youtube'].includes(key)) return s === '' || /^https?:\/\/\S+$/.test(s.trim()) ? s.trim() : '';
    if (['primary', 'accent', 'dark'].includes(key)) return HEX.test(s.trim()) ? s.trim() : tpl;
    return s;
  }
  if (typeof tpl === 'boolean') return !!value;
  if (Array.isArray(tpl)) {
    const item = tpl[0];
    return (Array.isArray(value) ? value : []).slice(0, 60).map((v) => sanitize(v, item, key));
  }
  if (isObj(tpl)) {
    const out = {};
    for (const k of Object.keys(tpl)) out[k] = sanitize(isObj(value) ? value[k] : undefined, tpl[k], k);
    return out;
  }
  return tpl;
}

// Слива запазеното с DEFAULTS (липсващите ключове остават по подразбиране)
function merge(stored, tpl = DEFAULTS) {
  const out = clone(tpl);
  if (!isObj(stored)) return out;
  for (const k of Object.keys(tpl)) {
    if (!(k in stored)) continue;
    if (isObj(tpl[k])) out[k] = merge(stored[k], tpl[k]);
    else out[k] = sanitize(stored[k], tpl[k], k);
  }
  return out;
}

module.exports = { DEFAULTS, merge, sanitize };
